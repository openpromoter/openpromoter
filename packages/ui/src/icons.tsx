/**
 * One icon family for the whole product: Phosphor (MIT), regular weight, filled for active states.
 * Names stay semantic (what the icon means here), so swapping a glyph is one line.
 * The SSR builds have no React context, so they work in server and client components alike.
 */
export type IconProps = Omit<React.SVGProps<SVGSVGElement>, "ref"> & {
  size?: number;
  /** Accepted for older call sites; Phosphor uses `weight` instead. */
  strokeWidth?: number;
  weight?: IconWeight;
};
export type Icon = React.ComponentType<IconProps>;
/** @deprecated kept so older call sites type-check; use `Icon`. */
export type LucideIcon = Icon;

function make(P: React.ComponentType<PhosphorProps>, name: string): Icon {
  const C = ({ size = 16, strokeWidth: _s, weight = "regular", ...rest }: IconProps) => (
    <P size={size} weight={weight} {...(rest as PhosphorProps)} />
  );
  C.displayName = name;
  return C;
}

