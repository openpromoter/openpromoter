import { chromium } from "@playwright/test";
const [out, scheme, tab] = process.argv.slice(2);
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 1280, height: 900 }, deviceScaleFactor: 2, colorScheme: scheme });
await p.goto("http://localhost:3000/login");
await p.getByLabel("Email").fill("demo@openpromoter.test");
await p.getByLabel("Password", { exact: true }).fill("openpromoter-demo");
await p.keyboard.press("Enter");
await p.waitForURL(/\/app\//);
await p.goto("http://localhost:3000/app/prg_iNTdb6irQktvHzjX/settings/import");
await p.waitForLoadState("networkidle");
if (tab) await p.getByRole("button", { name: tab, exact: true }).click();
await p.locator("main").screenshot({ path: out });
await b.close();
